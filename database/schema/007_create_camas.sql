CREATE TABLE IF NOT EXISTS habitaciones (
  id varchar(36) NOT NULL,
  numero smallint unsigned NOT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_habitaciones_numero (numero)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS camas (
  id varchar(36) NOT NULL,
  habitacion_id varchar(36) NOT NULL,
  estado enum('disponible', 'ocupado', 'bloqueado') NOT NULL DEFAULT 'disponible',
  PRIMARY KEY (id),
  KEY idx_camas_habitacion_id (habitacion_id),
  CONSTRAINT fk_camas_habitacion FOREIGN KEY (habitacion_id)
    REFERENCES habitaciones (id)
    ON UPDATE CASCADE
    ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

